''' Faça um programa que receba 5 valores digitados pelo usuário e, ao final, informe qual é a soma deles.'''

n1 = int(input("Digite o primeiro valor da soma: "))
n2 = int(input("Digite o segundo valor: "))
n3 = int(input("Digite o terceiro valor: "))
n4 = int(input("Digite o quarto valor: "))
n5 = int(input("Digite o ultimo valor: "))

resultado = n1 + n2 + n3 + n4 + n5
print(f"O valor da soma de todos os números é {resultado}")
